-- 仅当当前大厅属于该多版本玩法组时才返回配置
-- 避免同 gameid（如绍兴900046的30144）误用杭州等多版本大厅配置
function MutiVersionGameConfig.getMutiGameTable(gameID, lobbyID)
    local mutiGameTable = MutiVersionGameConfig.GameConfig[gameID]
    if not mutiGameTable or not lobbyID then
        return nil
    end
    for _, mutiGame in pairs(mutiGameTable) do
        if mutiGame.lobbyid == lobbyID then
            return mutiGameTable
        end
    end
    return nil
end

return MutiVersionGameConfig